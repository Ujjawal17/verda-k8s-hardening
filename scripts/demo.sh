#!/usr/bin/env bash
# Runs one blocked attempt per control and records command + output in docs/demo-log.md.
# Needs: the SSH tunnel to the API server (see README), KUBECONFIG=./kubeconfig, nmap, a TTY (Falco test).
set -uo pipefail   # no -e: blocked attempts are supposed to fail
cd "$(dirname "$0")/.."
export KUBECONFIG="$PWD/kubeconfig"
LOG=docs/demo-log.md
mapfile -t IPS < <(terraform -chdir=infra output -json node_ips | jq -r '.[]')
CP_IP="${IPS[0]}"
SSH=(ssh -o BatchMode=yes)
on() { local ip="$1"; shift; local j=(); [ "$ip" = "$CP_IP" ] || j=(-J "admin@$CP_IP"); "${SSH[@]}" "${j[@]}" "admin@$ip" sudo "$@"; }

# Write "$ cmd" + output + exit code to the log (and screen).
run() {
  { echo; echo '```console'; echo "\$ $*"; } >> "$LOG"
  out="$(eval "$@" 2>&1)"; rc=$?
  { echo "$out"; echo "# exit=$rc"; echo '```'; } >> "$LOG"
  echo "$out"
}
section() { printf '\n## %s\n\n%s\n' "$1" "$2" | tee -a "$LOG"; }

mkdir -p docs
printf '# Demo log\n\nGenerated by `scripts/demo.sh` on %s against the live cluster.\nEach section: the attempt, the block, and where it is visible.\n' "$(date -u +%FT%TZ)" > "$LOG"

section "0. Cluster" "3 nodes, all apps synced from Git by Argo CD."
run kubectl get nodes -o wide
run kubectl get applications -n argocd

section "1. Public surface" "Only cp-1:22 answers from the internet. Workers expose nothing. Root and password logins are refused."
for ip in "${IPS[@]}"; do run nmap -Pn -T4 --max-retries 1 -p- "$ip"; done
run "${SSH[@]}" -o PreferredAuthentications=publickey "root@$CP_IP" true
run "${SSH[@]}" -o PreferredAuthentications=password,keyboard-interactive -o PubkeyAuthentication=no "admin@$CP_IP" true
run on "$CP_IP" sshd -T '|' grep -E "'^(permitrootlogin|passwordauthentication|allowusers)'"
run on "$CP_IP" ufw status verbose
run kubectl create service nodeport probe --tcp=80 -n demo

section "2. Admission (Kyverno, PSS Restricted + custom)" "Server-side dry run: every bad spec is rejected by the API server before anything exists."
run kubectl apply --dry-run=server -f tests/kyverno/resources.yaml

section "3. GitOps trust boundary (Argo CD AppProject)" "The workloads project tries to deploy the platform-owned network policies: Argo CD refuses."
cat <<'EOF' > /tmp/demo-escape-app.yaml
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata: { name: demo-escape, namespace: argocd }
spec:
  project: workloads
  source: { repoURL: https://github.com/Ujjawal17/verda-k8s-hardening.git, targetRevision: main, path: tenancy/demo }
  destination: { server: https://kubernetes.default.svc, namespace: demo }
EOF
kubectl apply -f /tmp/demo-escape-app.yaml >/dev/null; sleep 20
run kubectl get application demo-escape -n argocd -o jsonpath="'{.status.conditions[*].message}'"
kubectl delete -f /tmp/demo-escape-app.yaml >/dev/null

section "4. Network (Cilium default-deny, L7, FQDN, metadata/kubelet deny, WireGuard)" "Allowed flows work, everything else is dropped and visible in Hubble."
WORKER_IP="${IPS[1]}"
run kubectl exec -n demo deploy/frontend -- wget -qO- -T 5 http://backend:9898/version
run kubectl exec -n demo deploy/frontend -- wget -qO- -T 5 --post-data=x http://backend:9898/echo
run kubectl exec -n demo deploy/backend -- wget -qO- -T 5 https://api.github.com/zen
run kubectl exec -n demo deploy/backend -- wget -qO- -T 5 https://example.com
run kubectl exec -n demo deploy/frontend -- wget -qO- -T 5 https://api.github.com/zen
run kubectl exec -n demo deploy/frontend -- wget -qO- -T 5 http://169.254.169.254/
run kubectl exec -n demo deploy/frontend -- wget -qO- -T 5 --no-check-certificate "https://$WORKER_IP:10250/pods"
for p in $(kubectl get pods -n kube-system -l k8s-app=cilium -o name); do
  run kubectl exec -n kube-system "$p" -c cilium-agent -- hubble observe --namespace demo --verdict DROPPED --last 20
done
run kubectl exec -n kube-system ds/cilium -c cilium-agent -- cilium-dbg encrypt status

section "5. Runtime detection (Falco)" "Interactive shell in a workload container: detected, then alerted (section 6)."
echo "\$ kubectl exec -it -n demo deploy/frontend -- sh -c 'id; exit'" >> "$LOG"
kubectl exec -it -n demo deploy/frontend -- sh -c 'id; exit'
sleep 30
run kubectl logs -n falco -l app.kubernetes.io/name=falco -c falco --since=5m '|' grep -E "'Terminal shell|K8S API'" '|' tail -5

section "6. Alerts (Prometheus)" "The attempts above fire the security alerts."
echo ">> waiting 3 minutes for rules to evaluate"; sleep 180
PROM_SVC="$(kubectl get svc -n monitoring -l app=kube-prometheus-stack-prometheus -o name | head -1)"
kubectl port-forward -n monitoring "$PROM_SVC" 9090:9090 >/dev/null 2>&1 & PF=$!; sleep 3
run curl -s localhost:9090/api/v1/alerts '|' jq "'[.data.alerts[] | {alert: .labels.alertname, state: .state, summary: .annotations.summary}]'"
kill "$PF"

section "7. Vulnerability + misconfig scanning (Trivy Operator)" "Continuous reports for every running image, plus CIS/NSA/PSS compliance reports."
run kubectl get vulnerabilityreports -A -o wide '|' head -20
run kubectl get clustercompliancereports

section "8. Secrets" "Git only holds ciphertext; app pods have no API token and no right to read Secrets; etcd encrypts Secrets at rest."
run head -20 monitoring/grafana-admin.sealed.yaml
run kubectl get secret grafana-admin -n monitoring
run kubectl auth can-i get secrets -n demo --as=system:serviceaccount:demo:default
run on "$CP_IP" /var/lib/rancher/rke2/bin/rke2 secrets-encrypt status

section "9. CIS benchmark (kube-bench, rke2-cis-1.9)" "Full output in docs/kube-bench-*.txt, summary here."
KB=v0.16.0; T=$(mktemp -d)
curl -sL -o "$T/kb.tgz" "https://github.com/aquasecurity/kube-bench/releases/download/$KB/kube-bench_${KB#v}_linux_amd64.tar.gz"
curl -sL -o "$T/sums" "https://github.com/aquasecurity/kube-bench/releases/download/$KB/kube-bench_${KB#v}_checksums.txt"
(cd "$T" && grep " kube-bench_${KB#v}_linux_amd64.tar.gz\$" sums | sed "s/ kube-bench.*/  kb.tgz/" | sha256sum -c -) || exit 1
for i in 0 1; do
  ip="${IPS[$i]}"; node=$([ "$i" = 0 ] && echo cp-1 || echo worker-1)
  targets=$([ "$i" = 0 ] && echo master,etcd,controlplane,policies || echo node)
  on "$ip" mkdir -p /opt/kube-bench
  on "$ip" tar -C /opt/kube-bench -xz < "$T/kb.tgz"
  on "$ip" /opt/kube-bench/kube-bench --config-dir /opt/kube-bench/cfg --benchmark rke2-cis-1.9 run --targets "$targets" > "docs/kube-bench-$node.txt"
  run grep -A6 "'== Summary total =='" "docs/kube-bench-$node.txt"
done

echo ">> demo log written to $LOG"
